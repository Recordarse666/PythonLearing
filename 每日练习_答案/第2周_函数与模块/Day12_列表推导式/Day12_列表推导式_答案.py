# ===== Day12_列表推导式 参考答案 =====

# 【题1】用推导式生成 1~10 的平方列表
squares = [x**2 for x in range(1, 11)]
print(squares)

# ==================================================

# 【题2】用推导式过滤出列表中的偶数
nums = [1, 2, 3, 4, 5, 6, 7, 8]
evens = [x for x in nums if x % 2 == 0]
print(evens)   # [2, 4, 6, 8]

# ==================================================

# 【题3】二维列表展开：[[1,2],[3,4],[5,6]] → [1,2,3,4,5,6]
matrix = [[1, 2], [3, 4], [5, 6]]
flat = [x for row in matrix for x in row]
print(flat)

# ==================================================

# 【题4】字典推导式：把 ["a","b","c"] 变成 {"a":0,"b":1,"c":2}
keys = ["a", "b", "c"]
d = {k: i for i, k in enumerate(keys)}
print(d)

# ==================================================

# 【题5】推导式+条件表达式：把列表中的负数变成0，正数保留
nums = [3, -1, 4, -5, 2]
result = [x if x > 0 else 0 for x in nums]
print(result)   # [3, 0, 4, 0, 2]

