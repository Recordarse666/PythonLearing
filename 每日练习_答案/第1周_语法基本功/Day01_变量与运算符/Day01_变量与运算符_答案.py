# 【题4】输入一个三位数，分别输出它的个位、十位、百位
num = int(input("请输入一个三位数: "))
ge = num % 10
shi = num // 10 % 10
bai = num // 100
print("个位:", ge, "十位:", shi, "百位:", bai)

