# 【题1】输入两个数，输出它们的和、差、积、商
a = float(input("请输入第一个数: "))
b = float(input("请输入第二个数: "))
print("和:", a + b)
print("差:", a - b)
print("积:", a * b)
if b != 0:
    print("商:", a / b)
else:
    print("除数不能为0")

