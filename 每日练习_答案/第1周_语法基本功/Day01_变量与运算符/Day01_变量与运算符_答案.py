# 【题2】输入一个年份，判断是否为闰年（能被4整除但不能被100整除，或能被400整除）
year = int(input("请输入年份: "))
if (year % 4 == 0 and year % 100 != 0) or year % 400 == 0:
    print(year, "是闰年")
else:
    print(year, "不是闰年")

