# 【题5】统计列表中出现次数最多的元素
lst = [1, 3, 2, 3, 4, 3, 2, 1, 3]
counts = {}
for x in lst:
    counts[x] = counts.get(x, 0) + 1
most = max(counts, key=counts.get)
print("出现最多:", most, "次数:", counts[most])   # 3, 4次

