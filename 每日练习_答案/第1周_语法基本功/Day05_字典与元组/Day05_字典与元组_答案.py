# 【题4】字典合并：把 {"a":1,"b":2} 和 {"b":3,"c":4} 合并（b的值取后者）
d1 = {"a": 1, "b": 2}
d2 = {"b": 3, "c": 4}
d1.update(d2)
print(d1)   # {"a":1, "b":3, "c":4}

