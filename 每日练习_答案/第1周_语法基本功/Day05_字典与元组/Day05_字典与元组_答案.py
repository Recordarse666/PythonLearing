# 【题2】用字典做一个学生成绩表：{姓名: 成绩}，实现查询、添加、修改、删除
scores = {"小明": 90, "小红": 85, "小刚": 60}
print("查询小明:", scores.get("小明"))
scores["小丽"] = 78        # 添加
scores["小刚"] = 95        # 修改
del scores["小红"]          # 删除
print(scores)

