# 理解面向对象
# 示例： 小狗吃食物（闻一闻smell、舔一舔lick、咬一咬bite）
# 	  分别采用面向过程和面向对象来分析

#类（Class）：具有相同特征和行为的一类对象的抽象描述（模板/图纸）。如「狗」。
# 对象（Object）：类的一个具体实例（instance），能完成特定事情的个体。如「旺财」这只具体的狗。
# 关系：类是模板，对象是根据模板造出来的具体存在。先有类，再有对象。
# 注意：面向对象是一种思想，不是编程语言；Python 是支持这种思想的语言。
# 面向过程:  先闻一闻, 然后再舔一舔, 最后再咬一咬 (注重过程)
# 面向对象:  小狗是一个对象, 它可以闻一闻食物, 可以舔一舔食物, 可以咬一咬食物. (不注重过程, 注重对象)
# 	    类（class）	        对象（object）
# 比喻	图纸/设计图	    按图纸盖出来的某一栋具体的房子
# 性质	抽象的定义、模板	具体的存在、实物
# 数量	一份	            可以盖很多栋
# 例子	Dog（狗这个物种）	旺财、大黄、来福（一只只具体的狗）
# 1. 面向过程:  先闻一闻, 然后再舔一舔, 最后再咬一咬 (注重过程)
def smell():
    print('闻一闻')
def lick():
    print('舔一舔')
def bite():
    print('咬一咬')
print('----- 面向过程：按步骤依次执行 -----')
smell()
lick()
bite()
# 2. 面向对象:  小狗是一个对象, 它可以闻一闻食物, 可以舔一舔食物, 可以咬一咬食物. (不注重过程, 注重对象)
class Dog:
    name='旺财'
    def smell(self):  # self 是占位符，运行时自动传入对象
        print(self.name,'闻一闻')

    def lick(self):
        print(self.name, '舔一舔')

    def bite(self):
        print(self.name, '咬一咬')

print('----- 面向对象：指挥对象去做 -----')
# 创建对象（实例化）：对象名 = 类名()
dog = Dog()

# 指挥对象去执行行为：对象名.方法名()
dog.smell()
dog.lick()
dog.bite()
#！！！！！！！！！！！！！！！！！！！！！！！！！！！！！！！！！！！！！
# 方法定义时：第一个参数必须写 self（名字约定俗成）。
# 方法调用时：不传 self，Python 自动传。
# self.name 的含义：访问「当前对象」的属性；self 里存的是这个对象的专属数据
